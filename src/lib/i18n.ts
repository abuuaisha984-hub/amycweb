export function ui(locale: Locale, key: string): string {
  const v = UI_STRINGS[locale]?.[key]
  if (v === null || v === undefined) return UI_STRINGS.en[key] ?? key
  return v
}

/**
 * Format a date according to locale.
 */
export function formatDate(date: Date | string, locale: Locale, opts?: Intl.DateTimeFormatOptions): string {
  const d = typeof date === "string" ? new Date(date) : date
  const loc = locale === "ar" ? "ar" : locale === "sw" ? "sw-TZ" : "en-GB"
  try {
    return new Intl.DateTimeFormat(loc, opts || { day: "numeric", month: "short", year: "numeric" }).format(d)
  } catch {
    return d.toLocaleDateString("en-GB", opts)
  }
}

export function formatDateTime(date: Date | string, locale: Locale): string {
  return formatDate(date, locale, { day: "numeric", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" })
}

// ── hreflang alternates helper for metadata ─────────────────────────────────
export function buildAlternates(pathWithoutLocale: string): Record<string, string> {
  const languages: Record<string, string> = {}
  for (const loc of LOCALES) {
    languages[loc] = `/${loc}${pathWithoutLocale}`
  }
  languages["x-default"] = `/en${pathWithoutLocale}`
  return languages
}
