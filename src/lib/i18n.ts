export const RTL_LOCALES: Locale[] = ["ar"]

export function isRTL(locale: Locale): boolean {
  return RTL_LOCALES.includes(locale)
}

export function isLocale(v: string | undefined): v is Locale {
  return v === "en" || v === "sw" || v === "ar"
}

/**
 * Parse a translations JSON string safely.
 */
export function parseTranslations(raw: string | null | undefined): Record<string, any> {
  if (!raw) return {}
  try {
    return JSON.parse(raw)
  } catch {
    return {}
  }
}

/**
 * Resolve a localized field value from an object's translations JSON.
 * Falls back to the English default when the requested locale is missing.
 */
export function localizedField(
  obj: { translations?: string | null } | null | undefined,
  field: string,
  locale: Locale,
  fallback: string
): string {
  if (!obj) return fallback
  if (locale === "en") return fallback
  const tr = parseTranslations(obj.translations)
  const loc = tr[locale]
  if (loc && typeof loc === "object" && loc[field]) return loc[field]
  return fallback
}

/**
 * Check whether a given locale has a translation for a field.
 */
export function hasTranslation(
  obj: { translations?: string | null } | null | undefined,
  locale: Locale,
  field?: string
): boolean {
  if (!obj || locale === "en") return true
  const tr = parseTranslations(obj.translations)
  const loc = tr[locale]
  if (!loc || typeof loc !== "object") return false
  if (field) return !!loc[field]
  return Object.values(loc).some((v) => !!v)
}

